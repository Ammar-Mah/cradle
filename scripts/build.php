<?php
/**
 * Builds installable release artifacts into dist/ (never edit dist/ by hand).
 *
 * Usage: php scripts/build.php [--out=dist] [--no-source]
 *
 * Produces:
 * - One ZIP per framework package (parent theme, core, each add-on), with canonical skills injected.
 * - An installable blank child theme ZIP, generated with the parent theme's own generator
 *   (packages/themes/cradle/bin/child-theme.php) with neutral defaults (slug cradle-child, name "Cradle Child").
 * - A copy-in kit: `wp-content/themes/{cradle,cradle-child}` + `wp-content/plugins/<every Cradle plugin>`, so a
 *   website can be started by copying one folder into a WordPress install, without running commands.
 * - The representative generated site (sites/sandbox) as development ZIPs (includes its brief and state).
 * - A developer source bundle (repository without wp/, wp-target/, dist/, VCS data).
 * - manifest.json (versions, sizes, sha256) and SHA256SUMS.
 *
 * Production package policy: framework ZIPs include public-safe AGENTS.md/CLAUDE.md/skills/docs.
 * The child starter includes only templates of briefs and state files, never a real site's private brief.
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}
if ( ! class_exists( 'ZipArchive' ) ) {
	fwrite( STDERR, "ZipArchive is required.\n" );
	exit( 1 );
}

require __DIR__ . '/lib/packages.php';

$root     = dirname( __DIR__ );
$manifest = cradle_manifest( $root );
$opts     = getopt( '', array( 'out::', 'no-source' ) );
$out      = $root . '/' . trim( $opts['out'] ?? 'dist', '/' );
$date     = gmdate( 'Y-m-d' );

if ( is_dir( $out ) ) {
	foreach ( glob( $out . '/*' ) as $old ) {
		if ( is_file( $old ) ) {
			unlink( $old );
		}
	}
} else {
	mkdir( $out, 0775, true );
}

$artifacts = array();

// 1. Framework packages (their files are also collected for the copy-in kit).
$kit = array();
foreach ( $manifest['packages'] as $pkg ) {
	if ( 'framework' !== ( $pkg['kind'] ?? '' ) || ! is_dir( $root . '/' . $pkg['source'] ) ) {
		continue;
	}
	$version = cradle_package_version( $root, $pkg );
	$files   = cradle_package_files( $root, $manifest, $pkg );
	$zip     = sprintf( '%s/%s-%s-%s.zip', $out, $pkg['name'], $pkg['type'], $version );
	build_zip( $zip, $pkg['name'], $files );
	$artifacts[] = artifact( $zip, $pkg['name'], $pkg['type'], $version, 'framework' );
	foreach ( $files as $rel => $entry ) {
		$kit[ $pkg['type'] . 's/' . $pkg['name'] . '/' . $rel ] = $entry;
	}
}

// 2. Blank child theme generated by the parent theme's generator with neutral defaults.
$tmp = sys_get_temp_dir() . '/cradle-build-' . bin2hex( random_bytes( 4 ) );
mkdir( $tmp, 0775, true );
$cmd = escapeshellarg( PHP_BINARY ) . ' ' . escapeshellarg( $root . '/packages/themes/cradle/bin/child-theme.php' ) . ' new --slug=cradle-child --name=' . escapeshellarg( 'Cradle Child' ) . ' --site-id=set-on-first-use --target=' . escapeshellarg( $tmp );
exec( $cmd, $output, $code );
if ( 0 !== $code ) {
	fwrite( STDERR, "Starter generation failed.\n" );
	exit( 1 );
}
$dir   = $tmp . '/cradle-child';
$files = array();
foreach ( cradle_list_files( $dir, $manifest['exclude'] ) as $rel ) {
	$files[ $rel ] = array( 'path' => $dir . '/' . $rel );
	$kit[ 'themes/cradle-child/' . $rel ] = array( 'content' => (string) file_get_contents( $dir . '/' . $rel ) );
}
$zip = sprintf( '%s/cradle-child-theme-starter-0.1.0.zip', $out );
build_zip( $zip, 'cradle-child', $files );
$artifacts[] = artifact( $zip, 'cradle-child', 'theme', '0.1.0', 'starter' );
remove_tree( $tmp );

// 2b. Copy-in kit: extract into the WordPress folder (the one with wp-config.php); it merges into wp-content.
$zip = sprintf( '%s/cradle-kit-%s.zip', $out, $date );
build_zip( $zip, 'wp-content', $kit );
$artifacts[] = artifact( $zip, 'cradle-kit', 'bundle', $date, 'copy-in-kit' );

// 2c. Copy-in update: the same parent and plugins without any child theme, so extracting it over an existing
// site can never replace the website's own child.
$update = array_filter( $kit, static fn( $rel ) => ! str_starts_with( $rel, 'themes/cradle-child/' ), ARRAY_FILTER_USE_KEY );
$zip    = sprintf( '%s/cradle-update-%s.zip', $out, $date );
build_zip( $zip, 'wp-content', $update );
$artifacts[] = artifact( $zip, 'cradle-update', 'bundle', $date, 'copy-in-update' );

// 3. Representative generated site (development bundle, includes brief and state).
foreach ( $manifest['packages'] as $pkg ) {
	if ( 'site' !== ( $pkg['kind'] ?? '' ) || ! is_dir( $root . '/' . $pkg['source'] ) ) {
		continue;
	}
	$version = cradle_package_version( $root, $pkg );
	$files   = cradle_package_files( $root, $manifest, $pkg );
	$zip     = sprintf( '%s/sandbox-site-%s-%s-%s-dev.zip', $out, $pkg['name'], $pkg['type'], $version );
	build_zip( $zip, $pkg['name'], $files );
	$artifacts[] = artifact( $zip, $pkg['name'], $pkg['type'], $version, 'representative-site-development' );
}

// 4. Developer source bundle.
if ( ! isset( $opts['no-source'] ) ) {
	$files = array();
	foreach ( cradle_list_files( $root, array() ) as $rel ) {
		$first = explode( '/', $rel )[0];
		if ( in_array( $first, array( 'wp', 'wp-target', 'dist', '.git', 'node_modules' ), true ) ) {
			continue;
		}
		// Keep the generated skill wrappers; drop machine-specific Claude Code settings (absolute hook paths).
		if ( str_starts_with( $rel, '.claude/' ) && ! str_starts_with( $rel, '.claude/skills/' ) ) {
			continue;
		}
		foreach ( $manifest['exclude'] as $pattern ) {
			foreach ( explode( '/', $rel ) as $segment ) {
				if ( fnmatch( $pattern, $segment ) ) {
					continue 3;
				}
			}
		}
		$files[ $rel ] = array( 'path' => $root . '/' . $rel );
	}
	$zip = sprintf( '%s/cradle-source-%s.zip', $out, $date );
	build_zip( $zip, 'cradle', $files );
	$artifacts[] = artifact( $zip, 'cradle-source', 'bundle', $date, 'developer-source' );
}

// 5. Manifest and checksums.
$compat = json_decode( (string) @file_get_contents( $root . '/compatibility.json' ), true );
file_put_contents(
	$out . '/manifest.json',
	json_encode(
		array(
			'schemaVersion' => 1,
			'built'         => gmdate( 'c' ),
			'compatibility' => $compat ?: null,
			'artifacts'     => $artifacts,
		),
		JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES
	) . "\n"
);
$sums = '';
foreach ( $artifacts as $a ) {
	$sums .= $a['sha256'] . '  ' . $a['file'] . "\n";
}
file_put_contents( $out . '/SHA256SUMS', $sums );

foreach ( $artifacts as $a ) {
	printf( "%-58s %8s KB  %s\n", $a['file'], number_format( $a['bytes'] / 1024, 0 ), substr( $a['sha256'], 0, 16 ) );
}
echo count( $artifacts ) . " artifacts written to {$out}\n";

function build_zip( string $zip_path, string $folder, array $files ) {
	$zip = new ZipArchive();
	if ( true !== $zip->open( $zip_path, ZipArchive::CREATE | ZipArchive::OVERWRITE ) ) {
		fwrite( STDERR, "Cannot write {$zip_path}\n" );
		exit( 1 );
	}
	ksort( $files );
	foreach ( $files as $rel => $entry ) {
		$name = $folder . '/' . $rel;
		if ( isset( $entry['content'] ) ) {
			$zip->addFromString( $name, $entry['content'] );
		} else {
			$zip->addFile( $entry['path'], $name );
		}
		$zip->setMtimeName( $name, 1767225600 ); // Fixed timestamp for reproducible archives.
	}
	$zip->close();
}

function artifact( string $zip, string $name, string $type, string $version, string $kind ): array {
	return array(
		'file'    => basename( $zip ),
		'package' => $name,
		'type'    => $type,
		'version' => $version,
		'kind'    => $kind,
		'bytes'   => filesize( $zip ),
		'sha256'  => hash_file( 'sha256', $zip ),
	);
}

function remove_tree( string $dir ) {
	$it = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ), RecursiveIteratorIterator::CHILD_FIRST );
	foreach ( $it as $item ) {
		$item->isDir() ? rmdir( $item->getPathname() ) : unlink( $item->getPathname() );
	}
	rmdir( $dir );
}
